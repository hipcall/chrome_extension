#!/usr/bin/env bash
# Builds dist/hipcall-webphone-<version>.zip with only the files the extension
# loads, after checking the JSON files. Prints the path of the ZIP.
#
#   scripts/package.sh
#
# Needs jq and zip (preinstalled on GitHub runners; `brew install jq` on macOS).
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

FILES=(manifest.json service_worker.js _locales fonts icons js src)

for f in manifest.json _locales/*/messages.json; do
  jq empty "$f" || { echo "Invalid JSON: $f" >&2; exit 1; }
done

# Every language must have exactly the keys of the English file.
for f in _locales/*/messages.json; do
  if ! diff <(jq -r 'keys[]' _locales/en/messages.json) <(jq -r 'keys[]' "$f") >&2; then
    echo "Keys of $f differ from _locales/en/messages.json (< missing, > extra)" >&2
    exit 1
  fi
done

VERSION="$(jq -r .version manifest.json)"
OUT="dist/hipcall-webphone-$VERSION.zip"

mkdir -p dist
rm -f "$OUT"
zip -qrX "$OUT" "${FILES[@]}" -x '*.DS_Store' -x 'manifest.json' -x 'js/oauth_clients.js' -x 'js/oauth_clients.example.js'

# manifest.json without "key": the key only pins the extension id for unpacked
# (development) builds; the Web Store item has its own.
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
jq 'del(.key)' manifest.json > "$TMP/manifest.json"
(cd "$TMP" && zip -qX "$OLDPWD/$OUT" manifest.json)

# OAuth client ids: from the environment (GitHub variables HC_OAUTH_CLIENT_TR /
# HC_OAUTH_CLIENT_GLOBAL in the release workflow), else the local js/oauth_clients.js.
mkdir -p "$TMP/js"
if [ -n "${HC_OAUTH_CLIENT_TR:-}${HC_OAUTH_CLIENT_GLOBAL:-}" ]; then
  for v in "${HC_OAUTH_CLIENT_TR:-}" "${HC_OAUTH_CLIENT_GLOBAL:-}"; do
    [[ -z "$v" || "$v" =~ ^[A-Za-z0-9_-]+$ ]] || { echo "Invalid OAuth client id" >&2; exit 1; }
  done
  jq -n --arg tr "${HC_OAUTH_CLIENT_TR:-}" --arg global "${HC_OAUTH_CLIENT_GLOBAL:-}" \
    '"// Generated by scripts/package.sh\n// eslint-disable-next-line no-var\nvar HC_OAUTH_CLIENTS = \({tr: $tr, global: $global});\n"' -r \
    > "$TMP/js/oauth_clients.js"
elif [ -f js/oauth_clients.js ]; then
  cp js/oauth_clients.js "$TMP/js/oauth_clients.js"
elif [ -n "${CI:-}" ]; then
  echo "HC_OAUTH_CLIENT_TR / HC_OAUTH_CLIENT_GLOBAL are not set: the release would have no Hipcall sign-in." >&2
  exit 1
else
  echo "Warning: no OAuth client ids (js/oauth_clients.js): Hipcall sign-in is off in this ZIP." >&2
fi
[ -f "$TMP/js/oauth_clients.js" ] && (cd "$TMP" && zip -qX "$OLDPWD/$OUT" js/oauth_clients.js)
echo "$OUT"
